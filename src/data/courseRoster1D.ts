/**
 * Normaliza cadenas para comparación insensible a mayúsculas, tildes y espacios
 */
export function normalizeStudentString(str: string): string {
  return (str || '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim();
}

/**
 * Verifica si un estudiante de la nómina ya fue reclamado o conectado en la sala actual
 */
export function isStudentAlreadyClaimed(
  student: CourseStudent,
  connectedParticipants: Array<{
    name?: string;
    firstName?: string;
    paternalLastName?: string;
    maternalLastName?: string;
    listNumber?: number;
    members?: string[];
  }>
): boolean {
  if (!connectedParticipants || connectedParticipants.length === 0) return false;

  const targetFull = normalizeStudentString(student.fullName);
  const targetSurname = normalizeStudentString(`${student.paternalLastName} ${student.maternalLastName}`);
  const targetReversed = normalizeStudentString(`${student.firstName} ${student.paternalLastName}`);

  return connectedParticipants.some((p) => {
    // 1. Verificación directa por número de lista oficial
    if (typeof p.listNumber === 'number' && p.listNumber === student.listNumber) {
      return true;
    }

    const pName = normalizeStudentString(p.name || '');
    const pCombined = normalizeStudentString(
      `${p.firstName || ''} ${p.paternalLastName || ''} ${p.maternalLastName || ''}`
    );
    const pReversed = normalizeStudentString(
      `${p.paternalLastName || ''} ${p.maternalLastName || ''} ${p.firstName || ''}`
    );

    // Revisar nombre directo con longitud mínima para evitar falsos positivos
    if (pName && pName.length >= 3) {
      if (
        pName.includes(targetSurname) ||
        (pCombined && pCombined.length >= 4 && pCombined.includes(targetSurname)) ||
        (pReversed && pReversed.length >= 4 && pReversed.includes(targetSurname)) ||
        (pName.length >= 6 && targetFull.includes(pName)) ||
        pName === targetFull ||
        pName === targetReversed
      ) {
        return true;
      }
    }

    // Revisar miembros si es grupo
    if (p.members && Array.isArray(p.members)) {
      return p.members.some((m) => {
        const mNorm = normalizeStudentString(m);
        return mNorm && mNorm.length >= 4 && (mNorm.includes(targetSurname) || (mNorm.length >= 6 && targetFull.includes(mNorm)));
      });
    }

    return false;
  });
}
